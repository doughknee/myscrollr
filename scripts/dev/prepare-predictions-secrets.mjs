#!/usr/bin/env node
/**
 * Extract the predictions channel's Kalshi credentials from its gitignored
 * `.env` into Docker-friendly files under `secrets/`:
 *
 *   - secrets/kalshi-private-key.pem   the RSA private key, as a real file
 *                                      (mounted into the container; Docker's
 *                                      env_file can't carry a multiline PEM)
 *   - secrets/predictions.docker.env   the single-line vars (KEY_ID, ENV)
 *
 * Values are NEVER printed — only which pieces were found. Idempotent: safe
 * to re-run on every `make up`. If channels/predictions/.env is missing, the
 * predictions containers are skipped (see the Makefile) rather than failing
 * the whole stack.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const ENV_PATH = resolve("channels/predictions/.env");
const OUT_DIR = resolve("secrets");
const PEM_PATH = resolve(OUT_DIR, "kalshi-private-key.pem");
const ENV_OUT = resolve(OUT_DIR, "predictions.docker.env");

let text;
try {
  text = readFileSync(ENV_PATH, "utf8");
} catch {
  console.error(
    `[prep] channels/predictions/.env not found — skipping predictions ` +
      `secret prep.\n      Run \`make kalshi-key\` to pull the key from ` +
      `scrollr-secrets, or create the .env, to enable the predictions channel.`,
  );
  process.exit(0); // non-fatal: the stack can run without predictions
}

/** Pull one var from the .env text. Handles double/single-quoted values that
 *  span multiple lines (the PEM), and plain single-line values. Returns
 *  undefined if absent. */
function readVar(name) {
  const dq = new RegExp(`^${name}="([\\s\\S]*?)"\\s*$`, "m");
  const sq = new RegExp(`^${name}='([\\s\\S]*?)'\\s*$`, "m");
  let m = text.match(dq);
  if (m) return m[1].replace(/\\n/g, "\n");
  m = text.match(sq);
  if (m) return m[1];
  m = text.match(new RegExp(`^${name}=(.*)$`, "m"));
  if (m) return m[1].replace(/\\n/g, "\n").trim();
  return undefined;
}

const keyId = readVar("KALSHI_API_KEY_ID");
const kEnv = readVar("KALSHI_ENV") ?? "";
let pem = readVar("KALSHI_PRIVATE_KEY");

const problems = [];
if (!keyId) problems.push("KALSHI_API_KEY_ID");
if (!pem) problems.push("KALSHI_PRIVATE_KEY");
if (problems.length) {
  console.error(
    `[prep] missing ${problems.join(", ")} in channels/predictions/.env — ` +
      `predictions will not start. Fix the .env or run \`make kalshi-key\`.`,
  );
  process.exit(1);
}

pem = pem.trim();
if (!pem.includes("BEGIN") || !pem.includes("PRIVATE KEY")) {
  console.error(
    "[prep] KALSHI_PRIVATE_KEY does not look like a PEM private key — aborting.",
  );
  process.exit(1);
}
if (!pem.endsWith("\n")) pem += "\n";

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(PEM_PATH, pem, { mode: 0o600 });
writeFileSync(
  ENV_OUT,
  `# Generated by scripts/dev/prepare-predictions-secrets.mjs — do not edit.\n` +
    `KALSHI_API_KEY_ID=${keyId}\n` +
    `KALSHI_ENV=${kEnv}\n`,
  { mode: 0o600 },
);

console.log(
  `[prep] wrote secrets/kalshi-private-key.pem + secrets/predictions.docker.env ` +
    `(key id ${keyId.length} chars, env "${kEnv || "prod"}"; values not shown).`,
);
