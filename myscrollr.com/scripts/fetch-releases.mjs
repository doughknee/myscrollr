#!/usr/bin/env node
/**
 * Fetch the desktop release history from GitHub at build time and write
 * it into `src/lib/releases.generated.ts` for the /releases page.
 *
 * Why build-time (same rationale as fetch-latest-version.mjs): the
 * GitHub REST API is rate-limited to 60 req/hour per IP for
 * unauthenticated callers, so the page renders a baked-in snapshot
 * instantly and only *refreshes* client-side (see
 * `src/lib/releases.ts#fetchLiveReleases`, which tolerates failure).
 *
 * Output-path note: derived via `fileURLToPath(new URL(...))`, NOT
 * `URL.pathname`. On Windows `URL.pathname` yields `/C:/...`, which
 * node:path treats as a relative-ish path and `mkdir` explodes with a
 * doubled drive letter (`C:\C:\...`) — the bug fetch-latest-version.mjs
 * still carries. Do not copy that pattern.
 *
 * Failure modes (NEVER exits non-zero):
 *   - Fetch fails (CI or local) -> write an EMPTY array, warn loudly,
 *     exit 0. A releases page showing its fallback state beats a failed
 *     deploy; the route also self-heals client-side via live fetch.
 *
 * Auth: set GITHUB_TOKEN to send `Authorization: Bearer` — optional,
 * useful in CI to dodge the shared-runner rate limit.
 *
 * The generated file is gitignored (repo-root .gitignore).
 */

import { mkdir, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

// Canonical repo path — GitHub 301-redirects to the renamed repo
// (doughknee/myscrollr) and fetch follows redirects by default.
const RELEASES_API_URL =
  'https://api.github.com/repos/brandon-relentnet/myscrollr/releases?per_page=50'
const OUTPUT_PATH = fileURLToPath(
  new URL('../src/lib/releases.generated.ts', import.meta.url),
)
const DESKTOP_TAG_PREFIX = 'desktop-v'

/**
 * Mirror of `parseHeadline` in `src/lib/releases.ts` — keep in sync.
 * (Duplicated because this script must run before any TS is compiled
 * and the generated module must stay self-contained.)
 */
function parseHeadline(name, body) {
  const emDash = name.lastIndexOf('—')
  if (emDash !== -1) {
    const after = name.slice(emDash + 1).trim()
    if (after) return after
  }
  const heading = /^##\s+(.+?)\s*$/m.exec(body)
  return heading ? heading[1].trim() : ''
}

/** Mirror of `mapGitHubRelease` in `src/lib/releases.ts` — keep in sync. */
function mapGitHubRelease(raw) {
  if (typeof raw !== 'object' || raw === null) return null
  const tag = typeof raw.tag_name === 'string' ? raw.tag_name : ''
  if (!tag.startsWith(DESKTOP_TAG_PREFIX)) return null
  const name = typeof raw.name === 'string' && raw.name !== '' ? raw.name : tag
  const body = typeof raw.body === 'string' ? raw.body : ''
  return {
    tag,
    version: tag.slice(DESKTOP_TAG_PREFIX.length),
    name,
    headline: parseHeadline(name, body),
    date: typeof raw.published_at === 'string' ? raw.published_at : '',
    body,
    url:
      typeof raw.html_url === 'string'
        ? raw.html_url
        : 'https://github.com/brandon-relentnet/myscrollr/releases',
    prerelease: raw.prerelease === true,
  }
}

async function fetchReleasesFromGitHub() {
  const headers = {
    Accept: 'application/vnd.github+json',
    'User-Agent': 'myscrollr.com prebuild',
  }
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`
  }
  const res = await fetch(RELEASES_API_URL, {
    headers,
    signal: AbortSignal.timeout(10_000),
  })
  if (!res.ok) {
    throw new Error(`GitHub API returned ${res.status} ${res.statusText}`)
  }
  const data = await res.json()
  if (!Array.isArray(data)) {
    throw new Error('GitHub API response is not an array')
  }
  return data.map(mapGitHubRelease).filter((entry) => entry !== null)
}

let releases = []
let source = 'github-api'

// One retry on transient failure, mirroring fetch-latest-version.mjs.
let lastErr
for (let attempt = 1; attempt <= 2; attempt++) {
  try {
    releases = await fetchReleasesFromGitHub()
    break
  } catch (err) {
    lastErr = err
    console.warn(
      `[prebuild:releases] attempt ${attempt}/2 failed: ${err?.message ?? err}`,
    )
    if (attempt < 2) await new Promise((r) => setTimeout(r, 1500))
  }
}

if (releases.length === 0 && lastErr) {
  source = 'empty-fallback'
  console.warn(
    '─'.repeat(72) +
      `\n[prebuild:releases] WARNING: could not fetch releases from GitHub` +
      `\n[prebuild:releases] (${lastErr?.message ?? lastErr})` +
      `\n[prebuild:releases] Writing an EMPTY release list so the build can` +
      `\n[prebuild:releases] proceed — /releases will show its fallback state` +
      `\n[prebuild:releases] and refresh client-side. NOT failing the build.\n` +
      '─'.repeat(72),
  )
}

const content = `// Auto-generated by scripts/fetch-releases.mjs at build time.
// Source: ${source} (${releases.length} releases)
// Do NOT edit by hand and do NOT import this module directly — it is
// gitignored and absent on fresh clones. Go through \`src/lib/releases.ts\`,
// which loads it via import.meta.glob and falls back to [] when missing.

// Self-contained structural copy of ReleaseEntry from ./releases.ts
// (generated code can't import from a module that may not exist yet
// at generation time — keep the shapes identical).
export interface ReleaseEntry {
  tag: string
  version: string
  name: string
  headline: string
  date: string
  body: string
  url: string
  prerelease: boolean
}

export const RELEASES: ReadonlyArray<ReleaseEntry> = ${JSON.stringify(releases, null, 2)}
`

await mkdir(dirname(OUTPUT_PATH), { recursive: true })
await writeFile(OUTPUT_PATH, content)

console.log(
  `[prebuild:releases] wrote ${releases.length} releases (source: ${source})`,
)
